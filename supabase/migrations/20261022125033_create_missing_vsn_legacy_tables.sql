
-- Tabelas legadas ausentes no VersusCRM. Mantidas separadas das tabelas multiempresa crm_*.
create table if not exists public.condominiums (
 id uuid primary key default gen_random_uuid(), normalized_name text not null unique, name text not null,
 cnpj text, address text, number text, complement text, neighborhood text, city text default 'São Paulo', state text default 'SP', cep text,
 features text[] not null default '{}', construction_year integer, delivery_year integer, units integer, towers integer, floors integer, builder text,
 source_urls jsonb not null default '[]'::jsonb, evidence text, confidence text, last_enriched_at timestamptz,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 legal_name text, trade_name text, cnae integer, cnae_description text, status text, opened_at date, phone text, email text, legal_nature text,
 capital_social numeric, unit_area_min numeric, unit_area_max numeric, unit_bedrooms_min integer, unit_bedrooms_max integer,
 unit_bathrooms_min integer, unit_bathrooms_max integer, unit_parking_min integer, unit_parking_max integer,
 unit_specs_evidence text, unit_specs_source_url text, unit_specs_extracted_at timestamptz, unit_specs_confidence text,
 fonte_unica boolean not null default false, cover_image_url text, page_published boolean not null default false, page_slug text
);
create table if not exists public.condominium_features_catalog (
 id bigint generated by default as identity primary key, slug text not null unique, name text not null unique,
 category text not null default 'lazer', created_at timestamptz not null default now()
);
create table if not exists public.condominium_feature_map (
 condominium_id uuid not null references public.condominiums(id) on delete cascade,
 feature_id bigint not null references public.condominium_features_catalog(id) on delete cascade,
 source_url text, source text not null default 'quintoandar', confidence text not null default 'high',
 extracted_at timestamptz not null default now(), primary key(condominium_id, feature_id)
);
create table if not exists public.condominium_proximity (
 id bigint generated by default as identity primary key, condominium_id uuid not null references public.condominiums(id) on delete cascade,
 category text not null, place_names text[] not null default '{}', description text, source_url text,
 source text not null default 'quintoandar', confidence text not null default 'high', extracted_at timestamptz not null default now()
);
create table if not exists public.condominium_cep_street_queue (
 id bigint generated by default as identity primary key, state text not null, city text not null, address text not null,
 status text not null default 'pending', request_id bigint, attempts integer not null default 0, response jsonb,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.condominiums_backup_20261013_1014 (like public.condominiums);
create table if not exists public.developers (
 id uuid primary key default gen_random_uuid(), name text not null, legal_name text, document text, phone text, email text,
 website text, address text, notes text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.developments (
 id uuid primary key default gen_random_uuid(), name text not null, developer_id uuid, property_type text, description text, address text,
 neighborhood text, city text, state text, cep text, delivery_date date, bedrooms integer, suites integer, bathrooms integer, parking integer,
 elevators integer, land_area numeric, built_area numeric, incorporation_registry text, starting_price numeric, entry_percent numeric,
 construction_months integer, monthly_installment numeric, intermediate_installments text, keys_balance_percent numeric,
 financing_available boolean, payment_notes text, amenities text[] not null default '{}', cover_image_url text,
 gallery_urls text[] not null default '{}', video_url text, brochure_url text, price_table_url text,
 featured boolean not null default false, published boolean not null default false, created_by uuid,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.development_plans (
 id uuid primary key default gen_random_uuid(), development_id uuid, name text, description text, area numeric, bedrooms integer,
 suites integer, bathrooms integer, parking integer, floor_plan_url text, price numeric, details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.leads (
 id uuid primary key default gen_random_uuid(), property_id uuid, nome text not null, whatsapp text not null, email text not null,
 interesse text, mensagem text, created_at timestamptz not null default now()
);
create table if not exists public.location_catalog (
 id bigint generated by default as identity primary key, city text not null default 'São Paulo', state text not null default 'SP',
 region text not null, neighborhood text not null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.owner_contacts (
 id uuid primary key default gen_random_uuid(), owner_id uuid not null, contact_type text not null, contact_value text not null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
-- Estruturas com IDs de usuários são criadas sem FK para auth; a migração de registros será validada separadamente.
create table if not exists public.owner_term_acceptances (
 id uuid primary key default gen_random_uuid(), user_id uuid not null, term_version text not null, accepted_at timestamptz not null default now()
);
create table if not exists public.property_owner_edit_requests (
 id uuid primary key default gen_random_uuid(), property_id uuid not null, owner_id uuid not null, changes jsonb not null,
 status text not null default 'pending', owner_message text, admin_note text, reviewed_by uuid, reviewed_at timestamptz,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.property_photo_optimization_log (
 id bigint generated by default as identity primary key, property_id uuid not null, photo_index integer not null, original_url text not null,
 original_path text not null, original_bytes bigint, optimized_url text, optimized_path text, optimized_bytes bigint,
 thumbnail_url text, thumbnail_path text, thumbnail_bytes bigint, saved_bytes bigint, saved_percent numeric,
 status text not null default 'done', error text, created_at timestamptz not null default now()
);
create table if not exists public.property_photo_optimization_queue (
 property_id uuid primary key, total_photos integer not null default 0, processable_photos integer not null default 0,
 next_index integer not null default 0, status text not null default 'pending', error text, started_at timestamptz,
 finished_at timestamptz, updated_at timestamptz not null default now()
);
create table if not exists public.site_settings (
 id boolean primary key default true, site_name text not null default 'VSN Imóveis', logo_url text, phone text, whatsapp text, email text,
 creci text, instagram text, facebook text, youtube text, address text, about text, updated_at timestamptz not null default now(),
 site_photo_url text, site_cover_url text, site_share_image_url text
);
create table if not exists public.tower (
 id uuid primary key default gen_random_uuid(), code text not null, name text not null, sort_order integer not null, active boolean not null default true
);
